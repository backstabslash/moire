const SHEBANG = /^#!\s*(?:\S*\/)?(?:env\s+(?:-\S+\s+)*)?([\w.+-]+)/;
const CPP_HEADER = /^\s*(?:class|namespace|template\s*<|public:|private:)|std::|#include\s*<\w+>\s*$/m;

function byName(name: string): string | undefined {
  if (FILENAMES[name]) return FILENAMES[name];
  if (/^(?:docker|container)file[.-]/.test(name)) return "docker";
  if (name.startsWith(".env.") || name === ".env") return "dotenv";
  if (/^tsconfig\..*json$/.test(name)) return "jsonc";
  if (name.endsWith(".blade.php")) return "blade";
  if (name.endsWith(".code-workspace")) return "jsonc";
  if (!name.includes(".", 1)) return undefined;
  const ext = name.slice(name.lastIndexOf(".") + 1);
  return EXTENSIONS[ext] ?? byKey.get(ext);
}

function shebang(text: string): string | undefined {
  if (!text.startsWith("#!")) return undefined;
  const program = SHEBANG.exec(text.split("\n", 1)[0])?.[1];
  return program && SHEBANGS[program.toLowerCase().replace(/[\d.]+$/, "")];
}

export function langFor(path: string, text?: string | null): string {
  const name = path.split("/").pop()!.toLowerCase();
  const lang = byName(name);
  if (lang === "c" && name.endsWith(".h") && text && CPP_HEADER.test(text.slice(0, 20_000))) return "cpp";
  const script = text ? shebang(text) : undefined;
  if (script && (!lang || lang === "text" || !name.includes(".", 1))) return script;
  return lang ?? "text";
}

export function fenceLang(info: string): string {
  const key = info.toLowerCase().replace(/^[{.]+/, "");
  return byKey.get(key) ?? EXTENSIONS[key] ?? FILENAMES[key] ?? FILENAMES[`.${key}`] ?? "text";
}
